import sys

# ==========================================================================
#	Modes
# ==========================================================================

NC         = "\033[0m"
BOLD       = "\033[1m"
ITAL       = "\033[3m"
UNDERLINE  = "\033[4m"

# ==========================================================================
#	Standard colors
# ==========================================================================

BLACK      = "\033[30m"
GRAY       = "\033[90m"
RED        = "\033[31m"
GREEN      = "\033[32m"
YELLOW     = "\033[33m"
SAND       = "\033[38;2;231;200;160m"
DARK_SAND  = "\033[38;2;212;163;115m"
ORANGE     = "\033[38;5;208m"
BLUE       = "\033[34m"
PURPLE     = "\033[35m"
HOT_PINK   = "\033[38;2;255;105;180m"
PINK       = "\033[38;2;255;182;193m"
CYAN       = "\033[36m"
WHITE      = "\033[37m"

L_GRAY     = "\033[38;2;173;165;165m"
L_GRAY2    = "\033[38;2;211;211;211m"

# ==========================================================================
#	Pastel colors
# ==========================================================================

P_GREEN    = "\033[38;2;173;235;179m"
P_DGREEN   = "\033[38;2;152;168;105m"
P_BLUE     = "\033[38;2;179;235;242m"
P_YELLOW   = "\033[38;2;255;234;150m"
P_PURPLE   = "\033[38;2;211;211;255m"
P_ORANGE   = "\033[38;2;255;178;127m"


"""
Display functions
"""
def info(tag: str, msg: str) -> None:
	print(f"{BOLD}{P_YELLOW}[{tag}]{NC} {msg}")

def warn(tag: str, msg: str) -> None:
	print(f"{BOLD}{P_ORANGE}[{tag}]{NC} {msg}", file=sys.stderr)

def error(tag: str, msg: str) -> None:
	print(f"{BOLD}{RED}[{tag}]{NC} {msg}", file=sys.stderr)